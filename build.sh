#!/usr/bin/env bash
# Builds Ringgit Log from src/ and checks that every script parses.
#
#   dist/                          the website (GitHub Pages): accounts, records and receipts on Supabase
#   ringgit-log.html               the Claude artifact version (storage and reading come from the Claude host)
#   supabase/functions/read/prompts.js
#                                  the prompt code, copied from src/01-core.js so the read Edge Function asks
#                                  Claude exactly what the app would
#
# Needs python3 and node. Settings for the website come from site.config.json.
set -euo pipefail
cd "$(dirname "$0")"
SHARED="src/01-core.js src/02-ui.js src/03-pages.js src/04-flows.js src/06-sheets.js"
cat src/00-artifact.js $SHARED src/05-app.js > .app.js
cat src/00-web.js $SHARED src/07-web.js src/05-app.js > .web.js
python3 - <<'PY'
import base64, json, os, re, shutil

cfg = json.load(open("site.config.json", encoding="utf-8"))
url, key, sbjs = cfg["supabaseUrl"].rstrip("/"), cfg["supabasePublishableKey"], cfg["supabaseJsVersion"]
assert re.fullmatch(r"https://[a-z0-9-]+\.supabase\.co", url), "supabaseUrl looks wrong"
assert re.fullmatch(r"[A-Za-z0-9_.\-]+", key) and not key.startswith("sb_secret_"), "use the publishable key, never a secret key"
assert re.fullmatch(r"\d+\.\d+\.\d+", sbjs), "supabaseJsVersion must be an exact version"

css = open("src/style.css", encoding="utf-8").read()
tpl = base64.b64encode(open("template/ringgit-log-template.xlsx", "rb").read()).decode("ascii")
tpl_js = '[\n"' + '",\n"'.join(tpl[i:i + 2000] for i in range(0, len(tpl), 2000)) + '"\n].join("")'

def assemble(head_path, js_path, out_path, check_path, web):
    head = open(head_path, encoding="utf-8").read()
    js = open(js_path, encoding="utf-8").read()
    assert js.count('"__TEMPLATE_B64__"') == 1, "template placeholder missing"
    js = js.replace('"__TEMPLATE_B64__"', tpl_js)
    if web:
        js = js.replace('"__SUPABASE_URL__"', json.dumps(url)).replace('"__SUPABASE_KEY__"', json.dumps(key))
        head = head.replace("__SUPABASE_URL__", url).replace("__SUPABASE_JS__", sbjs)
        assert "__SUPABASE" not in js + head, "a placeholder was left"
    assert "</script" not in js.lower(), "script would close early"
    out = head.replace("/*STYLE*/", css).replace("/*SCRIPT*/", js)
    open(out_path, "w", encoding="utf-8").write(out)
    pre, post = head.split("<script>\n", 1)[1].split("/*SCRIPT*/")
    open(check_path, "w", encoding="utf-8").write(pre + js + post.split("</script>")[0])
    print("built", out_path, len(out), "bytes")

assemble("src/head.html", ".app.js", "ringgit-log.html", ".check.js", False)

if os.path.isdir("dist"):
    shutil.rmtree("dist")
os.makedirs("dist")
assemble("src/head-web.html", ".web.js", "dist/index.html", ".check-web.js", True)
for name in os.listdir("web"):
    shutil.copy(os.path.join("web", name), os.path.join("dist", name))
open("dist/.nojekyll", "w").close()

core = open("src/01-core.js", encoding="utf-8").read()
parts = re.findall(r"/\* @prompts:begin \*/\n(.*?)/\* @prompts:end \*/", core, re.S)
assert len(parts) == 3, "expected three @prompts regions in src/01-core.js"
mod = ("// Generated by build.sh from src/01-core.js. Do not edit: change the app's source and rebuild.\n"
       "// The read Edge Function builds its prompts with these, so the website asks Claude exactly what the app would.\n"
       "let TODAY = \"\";\nexport function setToday(s) { TODAY = s; }\nfunction todayStr() { return TODAY; }\n\n"
       + "\n".join(parts) + "\nexport { extractPrompt, routePrompt, shotPrompt };\n")
os.makedirs("supabase/functions/read", exist_ok=True)
open("supabase/functions/read/prompts.js", "w", encoding="utf-8").write(mod)
open(".prompts-check.mjs", "w", encoding="utf-8").write(mod)
print("wrote supabase/functions/read/prompts.js", len(mod), "bytes")
PY
node --check .check.js && node --check .check-web.js && node --check .prompts-check.mjs && echo "syntax ok"
